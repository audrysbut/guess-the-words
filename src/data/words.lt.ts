const rawWordBankLt: Record<Theme, RawWordEntry[]> = {
  movies,
  actors,
  famous_people: famousPeople,
  books,
  fictional_characters: fictionalCharacters,
  video_games: videoGames,
}

const wordBankLt: Record<Theme, WordEntry[]> = {} as Record<Theme, WordEntry[]>

for (const key of Object.keys(rawWordBankLt) as Theme[]) {
  wordBankLt[key] = rawWordBankLt[key].map(entry => ({
    ...entry,
    theme: key,
  }))
}

export function getRandomWordLt(theme: Theme, usedWords: Set<string>): WordEntry | null {
  const words = wordBankLt[theme]
  if (!words || words.length === 0) return null

  const available = words.filter(w => !usedWords.has(w.answer))
  if (available.length === 0) return null

  const entry = available[Math.floor(Math.random() * available.length)]
  return entry
}
